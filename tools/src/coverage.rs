//! Writes vectors/COVERAGE.md: every rule tag ([R4.*], [PIN-*], [COV-*]) that a game vector
//! covers or a core test names in its doc comment, with those vectors and `test:<function>`
//! entries. `core/tests/coverage_index.rs` checks that every tag of README.md and of the
//! parity-testing skill is there, and that every entry exists.

use std::collections::BTreeMap;
use std::fs;
use std::path::Path;

/// The tags and functions of the `#[test]` functions under `core/src` and `core/tests` whose
/// doc comments name rule tags.
fn annotated_tests(root: &Path) -> Result<Vec<(String, String)>, String> {
    let mut found = Vec::new();
    for dir in ["core/src", "core/tests"] {
        let dir = root.join(dir);
        let mut files: Vec<_> = fs::read_dir(&dir)
            .map_err(|e| format!("{}: {e}", dir.display()))?
            .map(|entry| entry.map(|entry| entry.path()).map_err(|e| e.to_string()))
            .collect::<Result<_, _>>()?;
        files.retain(|path| path.extension().is_some_and(|ext| ext == "rs"));
        files.sort();
        for path in files {
            let text = fs::read_to_string(&path).map_err(|e| format!("{}: {e}", path.display()))?;
            found.extend(tests_in(&text));
        }
    }
    Ok(found)
}

/// (tag, function) for each tag in the doc comment right above a `#[test]` function.
fn tests_in(text: &str) -> Vec<(String, String)> {
    let mut found = Vec::new();
    let mut doc = String::new();
    let mut is_test = false;
    for line in text.lines().map(str::trim) {
        if let Some(comment) = line.strip_prefix("///") {
            doc.push_str(comment);
        } else if line.starts_with("#[") {
            is_test |= line == "#[test]";
        } else {
            let name = line
                .strip_prefix("fn ")
                .and_then(|rest| rest.split('(').next())
                .filter(|_| is_test);
            if let Some(name) = name {
                found.extend(tags(&doc).into_iter().map(|tag| (tag, name.to_string())));
            }
            doc.clear();
            is_test = false;
        }
    }
    found
}

/// The rule tags in `text`, written in brackets: [R4.<n>-<k>], [PIN-<nn>] or [COV-<nn>].
pub fn tags(text: &str) -> Vec<String> {
    text.split('[')
        .skip(1)
        .filter_map(|part| part.split(']').next())
        .filter(|tag| is_tag(tag))
        .map(str::to_string)
        .collect()
}

fn is_tag(tag: &str) -> bool {
    let numbered = |rest: &str| !rest.is_empty() && rest.chars().all(|c| c.is_ascii_digit());
    if let Some(rest) = tag.strip_prefix("R4.") {
        rest.split_once('-')
            .is_some_and(|(n, k)| numbered(n) && numbered(k))
    } else {
        ["PIN-", "COV-"]
            .iter()
            .any(|prefix| tag.strip_prefix(prefix).is_some_and(numbered))
    }
}

/// The order of the index: R4 tags by section and number, then PIN, then COV.
fn sort_key(tag: &str) -> (u8, u32, u32) {
    let number = |text: &str| text.parse().unwrap_or(u32::MAX);
    if let Some((n, k)) = tag
        .strip_prefix("R4.")
        .and_then(|rest| rest.split_once('-'))
    {
        (0, number(n), number(k))
    } else if let Some(n) = tag.strip_prefix("PIN-") {
        (1, number(n), 0)
    } else {
        (2, tag.strip_prefix("COV-").map_or(u32::MAX, number), 0)
    }
}

/// Writes the index of `vectors` (each vector's name and covers) and of the annotated tests.
pub fn write(root: &Path, vectors: &[(String, Vec<String>)]) -> Result<(), String> {
    let mut entries: BTreeMap<String, Vec<String>> = BTreeMap::new();
    for (name, covers) in vectors {
        for tag in covers.iter().filter(|cover| is_tag(cover)) {
            entries.entry(tag.clone()).or_default().push(name.clone());
        }
    }
    for (tag, function) in annotated_tests(root)? {
        let entry = entries.entry(tag).or_default();
        let test = format!("test:{function}");
        if !entry.contains(&test) {
            entry.push(test);
        }
    }
    let mut rows: Vec<(String, Vec<String>)> = entries.into_iter().collect();
    rows.sort_by_key(|(tag, _)| sort_key(tag));
    let table: String = rows
        .iter()
        .map(|(tag, covered_by)| format!("| [{tag}] | {} |\n", covered_by.join(", ")))
        .collect();
    let text = [
        "# Coverage index\n\n",
        "Generated by `cargo run -p jiro-tools --locked -- vectors`; never edit it by hand. Each rule ",
        "tag of README §4 ([R4.*] and [PIN-*]) and of the `parity-testing` skill ([COV-*]) maps to the ",
        "game vectors of `vectors/game/` that exercise it, from their `covers` field, and to the core ",
        "tests whose doc comments name it (`test:<function>`). `core/tests/coverage_index.rs` fails on ",
        "a tag with no entry, on an entry that does not exist, and on a tag that README.md and the ",
        "skill do not define.\n\n",
        "| Tag | Covered by |\n|---|---|\n",
        &table,
    ]
    .concat();
    let path = root.join("vectors/COVERAGE.md");
    fs::write(&path, text).map_err(|e| format!("{}: {e}", path.display()))?;
    println!("wrote {} tags to {}", rows.len(), path.display());
    Ok(())
}
