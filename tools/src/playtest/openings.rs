//! `playtest --openings` (plan M5.19): how soon straight cuts can split the two bosses of a
//! twin-boss level, or capture a large empty region, measured on the core.
//!
//! An opening plan is a straight line of cuts: a column from the bottom border up, a row from
//! either side border across, or every door of one bar closed in order. The player walks the rail
//! to the line's first cell, then cuts along it, resting on each claimed cell it reaches.
//!
//! - **Blind:** from tick 0, with no waiting: a plan made without reading the bosses.
//! - **Timed:** each cut waits for the first tick from which it closes without a hit. The core
//!   is deterministic, so this is the foresight of a player who knows the bosses' future; the
//!   earliest separation over all plans bounds what such a player does with straight cuts.
//!
//! playtest [--levels <dir>] --openings [--runs <n>] [--seed <n>] --out <file.md>

#[cfg(test)]
mod tests;

use std::fs;
use std::path::{Path, PathBuf};
use std::thread;

use jiro_core::game::Game;
use jiro_core::level::Level;
use jiro_core::types::{Cell, Dir, InputMask, Pos};

use super::{LevelFile, load_levels, nonce, number, percent};
use crate::scenarios::play::neighbor;

const USAGE: &str = "usage: jiro-tools playtest [--levels <dir>] --openings [--runs <n>] [--seed \
                     <n>] --out <file.md>";

/// Ticks after which a timed plan gives up, and the timed results are cut off.
pub(super) const HORIZON: u16 = 600;

/// The claim that counts as a large capture, in basis points.
pub(super) const LARGE_BP: u16 = 3_000;

/// The most ticks one cut of a line may take before it counts as stuck.
const CUT_TICKS: u16 = 80;

/// The most segments of one line: the field has at most a few bars across it.
const SEGMENTS: usize = 7;

#[derive(Clone, Copy, PartialEq, Eq)]
pub(super) enum Timing {
    Blind,
    Timed,
}

/// One cut of a plan: walk the rail to `start`, if given, then cut in `dir`.
#[derive(Clone, Copy)]
pub(super) struct Segment {
    start: Option<Pos>,
    dir: Dir,
}

/// How a plan ended: the tick of the separation, if any, and the claim it reached otherwise.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(super) struct End {
    pub(super) separated_at: Option<u16>,
    pub(super) claim_bp: u16,
}

/// The openings of one seed.
#[derive(Clone, Debug, PartialEq, Eq)]
pub(super) struct Seed {
    /// Whether a blind plan separates the bosses.
    pub(super) blind_split: bool,
    /// The largest claim of a blind plan that does not separate them.
    pub(super) blind_claim_bp: u16,
    /// The earliest tick at which a timed plan separates them, `HORIZON` if none does.
    pub(super) timed_split_at: u16,
    /// For each plan, in the order of `plans`, how its blind run ended.
    pub(super) blind: Vec<End>,
}

pub(super) fn run(args: &[&str]) -> Result<(), String> {
    let (mut levels, mut runs, mut seed, mut out) = (PathBuf::from("levels"), 1_000, 1, None);
    let mut rest = args;
    while let [flag, tail @ ..] = rest {
        match (*flag, tail) {
            ("--openings", _) => rest = tail,
            ("--levels", [value, tail @ ..]) => (levels, rest) = (PathBuf::from(value), tail),
            ("--runs", [value, tail @ ..]) => (runs, rest) = (number(flag, value)?, tail),
            ("--seed", [value, tail @ ..]) => (seed, rest) = (number(flag, value)?, tail),
            ("--out", [value, tail @ ..]) => (out, rest) = (Some(PathBuf::from(value)), tail),
            _ => return Err(USAGE.to_string()),
        }
    }
    let Some(out) = out else {
        return Err(USAGE.to_string());
    };
    if runs == 0 {
        return Err("--runs: at least 1".to_string());
    }
    let files = load_levels(&levels)?;
    let twins: Vec<&LevelFile> = files
        .iter()
        .filter(|level| level.level.second_boss.is_some())
        .collect();
    if twins.is_empty() {
        return Err(format!("{}: no level with two bosses", levels.display()));
    }
    let mut markdown = format!(
        "# Openings\n\nGenerated by `jiro-tools playtest --openings`: seed {seed}, {runs} run \
         nonces per level, those of `jiro-tools playtest`. An opening is a straight line of cuts \
         (a column from the bottom border, a row from a side border, or every door of one bar), \
         walked to on the rail and cut with a rest on each claimed cell. Blind: from tick 0 with \
         no waiting. Timed: each cut waits for the first tick from which it closes without a \
         hit, which the core's determinism allows. Large capture: {LARGE_BP} bp or more.\n\n\
         The best fixed line is the one plan that works on the most seeds; the other blind \
         columns take, on each seed, the best of all plans.\n\n\
         | # | Name | Best fixed line: split | Best fixed line: capture ≥ {LARGE_BP} bp | Any line: \
         split | Any line: capture ≥ {LARGE_BP} bp | Any line: capture median (bp) | Timed \
         split: min / median / Q3 tick | Timed split before tick 150 |\n\
         |---|---|---|---|---|---|---|---|---|\n"
    );
    for level in twins {
        let seeds = measure(&level.level, seed, runs);
        markdown.push_str(&row(level, &seeds));
    }
    write(&out, &markdown)
}

fn write(out: &Path, text: &str) -> Result<(), String> {
    if let Some(parent) = out.parent().filter(|dir| !dir.as_os_str().is_empty()) {
        fs::create_dir_all(parent).map_err(|e| format!("{}: {e}", parent.display()))?;
    }
    fs::write(out, text).map_err(|e| format!("{}: {e}", out.display()))?;
    println!("wrote {}", out.display());
    Ok(())
}

/// The openings of run nonces 0 to `runs` − 1, in nonce order, measured in parallel.
pub(super) fn measure(level: &Level, seed: u64, runs: u32) -> Vec<Seed> {
    let threads = thread::available_parallelism().map_or(1, |n| n.get() as u32);
    let mut seeds: Vec<(u32, Seed)> = thread::scope(|scope| {
        let handles: Vec<_> = (0..threads)
            .map(|t| {
                scope.spawn(move || {
                    (t..runs)
                        .step_by(threads as usize)
                        .map(|k| {
                            let game = Game::new(level, &nonce(seed, k), 0).expect("a valid level");
                            (k, openings(&game))
                        })
                        .collect::<Vec<_>>()
                })
            })
            .collect();
        handles
            .into_iter()
            .flat_map(|handle| handle.join().expect("an openings thread panicked"))
            .collect()
    });
    seeds.sort_by_key(|(k, _)| *k);
    seeds.into_iter().map(|(_, seed)| seed).collect()
}

fn row(level: &LevelFile, seeds: &[Seed]) -> String {
    let n = seeds.len();
    let names: Vec<String> =
        plans(&Game::new(&level.level, &nonce(0, 0), 0).expect("a valid level"))
            .into_iter()
            .map(|(name, _)| name)
            .collect();
    let best = |counts: &dyn Fn(&End) -> bool| -> (usize, &str) {
        (0..names.len())
            .map(|i| {
                (
                    seeds.iter().filter(|seed| counts(&seed.blind[i])).count(),
                    names[i].as_str(),
                )
            })
            .max_by_key(|(count, _)| *count)
            .expect("at least one plan")
    };
    let (split_count, split_plan) = best(&|end| end.separated_at.is_some());
    let (capture_count, capture_plan) =
        best(&|end| end.separated_at.is_none() && end.claim_bp >= LARGE_BP);
    let share = |count: usize| percent((count * 1_000 / n) as u32);
    let mut claims: Vec<u16> = seeds.iter().map(|seed| seed.blind_claim_bp).collect();
    let mut ticks: Vec<u16> = seeds.iter().map(|seed| seed.timed_split_at).collect();
    claims.sort_unstable();
    ticks.sort_unstable();
    let at = |sorted: &[u16], k: usize| sorted[(n - 1) * k / 4];
    format!(
        "| {:02} | {} | {} ({split_plan}) | {} ({capture_plan}) | {} | {} | {} | {} / {} / {} | {} |\n",
        level.index,
        level.name,
        share(split_count),
        share(capture_count),
        share(seeds.iter().filter(|seed| seed.blind_split).count()),
        share(claims.iter().filter(|&&claim| claim >= LARGE_BP).count()),
        at(&claims, 2),
        ticks[0],
        at(&ticks, 2),
        at(&ticks, 3),
        share(ticks.iter().filter(|&&tick| tick < 150).count()),
    )
}

/// The blind and timed openings of the game at tick 0.
pub(super) fn openings(game: &Game) -> Seed {
    let plans = plans(game);
    let mut seed = Seed {
        blind_split: false,
        blind_claim_bp: 0,
        timed_split_at: HORIZON,
        blind: Vec::with_capacity(plans.len()),
    };
    for (_, plan) in &plans {
        let blind = run_plan(game, plan, Timing::Blind);
        seed.blind.push(blind);
        match blind.separated_at {
            Some(_) => seed.blind_split = true,
            None => seed.blind_claim_bp = seed.blind_claim_bp.max(blind.claim_bp),
        }
        if let Some(tick) = run_plan(game, plan, Timing::Timed).separated_at {
            seed.timed_split_at = seed.timed_split_at.min(tick);
        }
    }
    seed
}

/// Every opening plan of the field as `game` holds it, with its name.
pub(super) fn plans(game: &Game) -> Vec<(String, Vec<Segment>)> {
    let at = |x: u8, y: u8| Pos { x, y };
    let line = |start: Pos, dir: Dir| -> Vec<Segment> {
        std::iter::once(Segment {
            start: Some(start),
            dir,
        })
        .chain(std::iter::repeat_n(
            Segment { start: None, dir },
            SEGMENTS - 1,
        ))
        .collect()
    };
    let mut plans: Vec<(String, Vec<Segment>)> = (1..59)
        .map(|x| (format!("column {x} up"), line(at(x, 59), Dir::Up)))
        .collect();
    for y in 1..59 {
        plans.push((format!("row {y} rightwards"), line(at(0, y), Dir::Right)));
        plans.push((format!("row {y} leftwards"), line(at(59, y), Dir::Left)));
    }
    for y in 1..59 {
        let doors = doors(game, y);
        if !doors.is_empty() {
            plans.push((format!("the doors of row {y}, rightwards"), doors.clone()));
            plans.push((
                format!("the doors of row {y}, leftwards"),
                doors.into_iter().rev().collect(),
            ));
        }
    }
    plans
}

/// The doors of a bar on row `y`: each run of open cells between claimed cells, closed from the
/// claimed cell on its left. A row with fewer than 10 claimed interior cells holds no bar.
fn doors(game: &Game, y: u8) -> Vec<Segment> {
    let open = |x: u8| game.grid.at(Pos { x, y }) == Some(Cell::Empty);
    if (1..59).filter(|&x| !open(x)).count() < 10 {
        return Vec::new();
    }
    (1..59)
        .filter(|&x| open(x) && !open(x - 1))
        .map(|x| Segment {
            start: Some(Pos { x: x - 1, y }),
            dir: Dir::Right,
        })
        .collect()
}

/// Plays `plan` on a copy of `start`, stopping at the separation, at the first segment that
/// fails, or at the horizon.
pub(super) fn run_plan(start: &Game, plan: &[Segment], timing: Timing) -> End {
    let mut game = start.clone();
    for segment in plan {
        let done = segment.start.is_none_or(|to| walk(&mut game, to))
            && cut(&mut game, segment.dir, timing);
        if game.separated {
            return End {
                separated_at: Some(game.ticks_used),
                claim_bp: game.claim_bp().unwrap_or(0),
            };
        }
        if !done || game.end.is_some() || game.ticks_used >= HORIZON {
            break;
        }
    }
    End {
        separated_at: None,
        claim_bp: game.claim_bp().unwrap_or(0),
    }
}

/// Steps `mask`; false once the level has ended other than by a separation.
fn step(game: &mut Game, mask: InputMask) -> bool {
    let end = game.step(mask).expect("the core steps a valid game");
    end.is_none() || game.separated
}

fn rail(game: &Game, pos: Pos) -> bool {
    game.grid.at(pos) == Some(Cell::Claimed) && game.grid.is_rail(pos)
}

/// Walks a shortest path on the rail to `to`; false if there is none or the level ends.
fn walk(game: &mut Game, to: Pos) -> bool {
    let Some(path) = rail_path(game, to) else {
        return false;
    };
    path.into_iter().all(|dir| step(game, dir.mask())) && game.player.pos == to
}

/// The directions of a shortest walk on the rail from the player to `to`.
fn rail_path(game: &Game, to: Pos) -> Option<Vec<Dir>> {
    let index = |pos: Pos| usize::from(pos.y) * 60 + usize::from(pos.x);
    let mut came: Vec<Option<(Pos, Dir)>> = vec![None; 3_600];
    let mut seen = vec![false; 3_600];
    let from = game.player.pos;
    seen[index(from)] = true;
    let mut queue = std::collections::VecDeque::from([from]);
    while let Some(pos) = queue.pop_front() {
        if pos == to {
            let mut path = Vec::new();
            let mut at = pos;
            while let Some((before, dir)) = came[index(at)] {
                path.push(dir);
                at = before;
            }
            path.reverse();
            return Some(path);
        }
        for dir in Dir::PRIORITY {
            if let Some(next) = neighbor(pos, dir)
                && !seen[index(next)]
                && rail(game, next)
            {
                seen[index(next)] = true;
                came[index(next)] = Some((pos, dir));
                queue.push_back(next);
            }
        }
    }
    None
}

/// From the player's cell, walks on claimed cells in `dir`, then cuts in `dir` until the cut
/// closes: at once when blind, or from the first tick from which it closes without a hit when
/// timed. False if the cut does not close.
fn cut(game: &mut Game, dir: Dir, timing: Timing) -> bool {
    while let Some(next) = neighbor(game.player.pos, dir)
        && game.grid.at(next) == Some(Cell::Claimed)
    {
        if !step(game, dir.mask()) || game.player.pos != next {
            return false;
        }
    }
    if neighbor(game.player.pos, dir).and_then(|next| game.grid.at(next)) != Some(Cell::Empty) {
        return false;
    }
    let mut waited = game.clone();
    loop {
        if let Some(closed) = closed_cut(&waited, dir) {
            *game = closed;
            return true;
        }
        if timing == Timing::Blind
            || waited.ticks_used >= HORIZON
            || !step(&mut waited, InputMask::NONE)
        {
            return false;
        }
    }
}

/// The game after a cut in `dir` from the player's cell closes without a hit, if it does.
fn closed_cut(game: &Game, dir: Dir) -> Option<Game> {
    let mut cutting = game.clone();
    let (lives, captured) = (game.player.lives, game.captured);
    for _ in 0..CUT_TICKS {
        if !step(&mut cutting, dir.mask()) || cutting.player.lives < lives {
            return None;
        }
        if !cutting.player.cutting && (cutting.captured != captured || cutting.separated) {
            return Some(cutting);
        }
    }
    None
}
